"""Phosphor 아이콘(MIT)을 받아 src/JackBean.App/Icons/PhosphorIcons.g.cs 로 만든다.

사용: python scripts/gen-phosphor-icons.py
- duotone: 투명 채움 층(opacity 0.2 경로)과 윤곽 층으로 나눠 담는다.
- regular: 윤곽만 (채움 층 없음).
버전을 올릴 때는 VERSION만 바꿔서 다시 돌린다.
"""
import re
import sys
import urllib.request
from pathlib import Path

VERSION = "2.1.1"
BASE = f"https://cdn.jsdelivr.net/npm/@phosphor-icons/core@{VERSION}/assets"

# 단순한 기호(+ x ✓)는 작은 크기에서 옅은 채움 사각형이 윤곽과 겹쳐 흐려 보인다 — 채움 층 없이 윤곽만 담는다.
# 같은 duotone 파일의 윤곽 층이라 선 굵기·모양은 다른 아이콘과 같다(CLAUDE.md "아이콘" 참고).
OUTLINE_ONLY = {"plus", "x", "check"}

# 앱에서 부르는 이름 -> (phosphor 이름, 두께)
ICONS = {
    # 앱 바
    "settings": ("gear", "duotone"),
    "info": ("info", "duotone"),
    # 설정 창: 모드(시스템·라이트·다크), 구역, 색 구성(고대비)
    "monitor": ("desktop", "duotone"),
    "sun": ("sun", "duotone"),
    "moon": ("moon", "duotone"),
    "palette": ("palette", "duotone"),
    "contrast": ("circle-half", "duotone"),
    # 글꼴 고르기 버튼의 화살표
    "caret-down": ("caret-down", "duotone"),
    # 알림(스낵바): 오류 표시, 복사, 복사됨, 닫기
    "warning": ("warning-circle", "duotone"),
    "copy": ("copy", "duotone"),
    "check": ("check", "duotone"),
    "x": ("x", "duotone"),
    # 빈 상태·정책 복구
    "tray": ("tray", "duotone"),
    "file-text": ("file-text", "duotone"),
    "reset": ("arrow-counter-clockwise", "duotone"),
    # 앱 편집 창
    "plus": ("plus", "duotone"),
    "trash": ("trash", "duotone"),
    "edit": ("pencil-simple", "duotone"),
    "folder": ("folder-open", "duotone"),
    # 규칙 편집 창: 앱 순서 바꾸기
    "arrow-up": ("arrow-up", "duotone"),
    "arrow-down": ("arrow-down", "duotone"),
}


def fetch(name: str, weight: str) -> str:
    suffix = "" if weight == "regular" else f"-{weight}"
    url = f"{BASE}/{weight}/{name}{suffix}.svg"
    with urllib.request.urlopen(url) as r:
        return r.read().decode("utf-8")


def layers(svg: str, key: str) -> tuple[str, str]:
    if re.search(r"<(circle|rect|line|polyline|polygon|ellipse)\b", svg):
        sys.exit(f"{key}: path 이외의 도형이 있다")
    fill, outline = [], []
    for tag in re.findall(r"<path\b[^>]*>", svg):
        d = re.search(r'\bd="([^"]+)"', tag).group(1)
        (fill if 'opacity="0.2"' in tag else outline).append(d)
    return " ".join(fill), " ".join(outline)


def main() -> None:
    rows = []
    for key, (name, weight) in ICONS.items():
        fill, outline = layers(fetch(name, weight), key)
        if key in OUTLINE_ONLY:
            fill = ""
        if not outline:
            sys.exit(f"{key}: 윤곽이 비었다")
        rows.append(f'        ["{key}"] = ("{fill}", "{outline}"),')
    out = Path(__file__).resolve().parent.parent / "src/JackBean.App/Icons/PhosphorIcons.g.cs"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// <auto-generated> scripts/gen-phosphor-icons.py 가 만든다. 직접 고치지 않는다.\n"
        f"// Phosphor Icons {VERSION} (MIT) https://phosphoricons.com\n"
        "namespace JackBean.App.Icons;\n\n"
        "internal static partial class PhosphorIcons\n{\n"
        "    /// <summary>이름 → (채움 층, 윤곽 층). 둘 다 256×256 격자의 경로 데이터.</summary>\n"
        "    public static readonly Dictionary<string, (string Fill, string Outline)> Data = new()\n    {\n"
        + "\n".join(rows)
        + "\n    };\n}\n",
        encoding="utf-8",
    )
    print(f"{len(rows)}개 -> {out}")


main()
